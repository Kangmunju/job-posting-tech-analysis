import pandas as pd

# 분석 파일에서 공통으로 사용하는 로더·직무 정보·스킬 매트릭스 함수 import
import _common as C


# =====================================================================
# 1. EDA 실행
# =====================================================================


def main():

    # DB 전체 공고 로드 + 제목 기준 직무 재분류
    df = C.load_jobs()

    C.rule(f"a1 EDA — 총 공고 {len(df):,}건 (원티드, 인증키 불필요)")

    # =================================================================
    # 2. 수집 카테고리 × 재분류 직무 교차표
    # =================================================================

    print("\n[수집 카테고리 → 텍스트 재분류(role)] 교차표")

    # category_name : 원티드에서 수집할 때 사용한 카테고리
    # role : classify.py에서 공고 제목을 보고 다시 분류한 직무
    # crosstab()으로 각 조합의 데이터 수를 셈
    ct = pd.crosstab(
        df["category_name"],
        df["role"],
    )

    # 분석 대상 5개 직무 + 풀스택 + other 순서로 출력
    cols = []

    for column in C.ROLE_ORDER + ["fullstack", "other"]:
        if column in ct.columns:
            cols.append(column)

    print(ct[cols].to_string())

    # =================================================================
    # 3. 분석 대상 공고 수
    # =================================================================

    # 본격적인 직무별 기술 분석에서는 df 전체가 아닌 sub(분석 대상 5개 직무)를 사용할 것
    sub = df[df["role"].isin(C.ROLE_ORDER)].copy()

    fullstack_count = int((df["role"] == "fullstack").sum())
    other_count = int((df["role"] == "other").sum())

    # 분석 대상 + 풀스택 + other가 전체 공고 수와 같아야 함 (분류 누락·중복 방지)
    if len(sub) + fullstack_count + other_count != len(df):
        raise RuntimeError("직무별 공고 수의 합이 전체 공고 수와 다릅니다.")

    print(
        f"\n분석 대상(5직무) 공고: {len(sub):,}건 "
        f"/ 제외: 풀스택 {fullstack_count:,}건, other {other_count:,}건"
    )

    print("\n[직무별 공고 수]")

    for role in C.ROLE_ORDER:
        count = (sub["role"] == role).sum()

        print(f"{C.ROLE_KO[role]:20s} {count:,}건")

    # =================================================================
    # 4. 직무별 요구 경력
    # =================================================================

    print("\n[직무별 요구 경력 하한 중앙값 / 신입가능 비율]")

    # 경력 정보가 실제로 존재하는 공고들의 경력 수준을 파악하기 위해 결측값 제거
    # 일부 고경력 공고가 섞이는 것을 방지하기 위해 중앙값을 사용함
    for role in C.ROLE_ORDER:
        annual = sub[sub["role"] == role]["annual_from"].dropna()

        median_year = annual.median()

        newbie_rate = (annual == 0).mean() * 100

        print(
            f"{C.ROLE_KO[role]:20s} "
            f"중앙값 {median_year:.1f}년 "
            f"신입가능 {newbie_rate:.0f}%"
        )

    # =================================================================
    # 5. 스킬 추출 커버리지
    # =================================================================

    mat, _ = C.build_skill_matrix(df)

    # role을 제외한 90개의 스킬 열만 선택
    skill_cols = [column for column in mat.columns if column != "role"]

    per_job = mat[skill_cols].sum(axis=1)

    # 스킬이 하나도 안 잡힌 공고 수
    zero_count = (per_job == 0).sum()

    # 스킬 0개 공고의 비율
    zero_rate = (per_job == 0).mean() * 100

    print(
        f"\n[스킬 추출 커버리지] "
        f"공고당 평균 스킬 {per_job.mean():.1f}개, "
        f"중앙값 {per_job.median():.0f}개"
    )

    print(f"스킬 0개 공고: {zero_count:,}건 ({zero_rate:.1f}%)")


# =====================================================================
# 6. 실행
# =====================================================================

if __name__ == "__main__":
    main()


